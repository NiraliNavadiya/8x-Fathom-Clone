"use client";

import { AlertTriangle, FileText } from "lucide-react";
import { useState } from "react";
import { cn } from "cn";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import type { SummaryTemplate } from "@/generated/prisma/enums";
import type { SummaryView } from "@/lib/meetings";
import type { SummaryContent } from "@/lib/summaries";
import { CopyButton } from "./copy-button";
import { summaryToText } from "./copy-text";

export const TEMPLATES: { value: SummaryTemplate; label: string; description: string }[] = [
  { value: "AI_NOTES", label: "AI Notes", description: "Overview and topic-by-topic notes" },
  { value: "MEETING_MINUTES", label: "Meeting Minutes", description: "Attendees, agenda, decisions, next steps" },
  { value: "SUMMARY", label: "Summary", description: "TL;DR and key points" },
  { value: "CUSTOMER_FEEDBACK", label: "Customer Feedback", description: "Feedback, pain points, requests" },
  { value: "PROJECT_MEETING", label: "Project Meeting", description: "Goal, status, workstreams, risks" },
];

export function SummaryTab({ summaries }: { summaries: SummaryView[] }) {
  const [template, setTemplate] = useState<SummaryTemplate>(
    () => TEMPLATES.find((t) => summaries.some((s) => s.template === t.value))?.value ?? "AI_NOTES",
  );
  const summary = summaries.find((s) => s.template === template);
  const meta = TEMPLATES.find((t) => t.value === template)!;

  return (
    <div className="grid gap-5">
      <div className="flex flex-wrap items-center gap-3">
        <label htmlFor="summary-template" className="text-sm text-muted-foreground">
          Template
        </label>
        <Select
          value={template}
          onValueChange={(v) => v && setTemplate(v as SummaryTemplate)}
          items={TEMPLATES.map((t) => ({ value: t.value, label: t.label }))}
        >
          <SelectTrigger id="summary-template" className="min-w-52 border-primary/40 bg-accent/40 font-medium">
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            {TEMPLATES.map((t) => {
              const available = summaries.some((s) => s.template === t.value && s.content);
              return (
                <SelectItem key={t.value} value={t.value}>
                  <span className="flex flex-col">
                    <span>{t.label}</span>
                    <span className="text-xs text-muted-foreground">
                      {available ? t.description : "Not available yet"}
                    </span>
                  </span>
                </SelectItem>
              );
            })}
          </SelectContent>
        </Select>
        {summary?.content != null && (
          <div className="ml-auto">
            <CopyButton label={`Copy ${meta.label}`} text={() => `${meta.label}

${summaryToText(template, summary.content)}`} />
          </div>
        )}
      </div>

      <div key={template} className="animate-in fade-in-0 duration-200 motion-reduce:animate-none">
        <div className="mb-4">
          <h2 className="text-base font-semibold">{meta.label}</h2>
          {summary?.content != null && <Provenance summary={summary} />}
        </div>
        {!summary || summary.status === "PENDING" ? (
          <Empty>
            {summary?.status === "PENDING"
              ? `${meta.label} is being prepared.`
              : `No ${meta.label} for this meeting yet. Generating summaries isn't available yet.`}
          </Empty>
        ) : summary.status === "FAILED" || summary.invalid ? (
          <div role="alert" className="flex items-start gap-3 rounded-xl border border-destructive/40 bg-destructive/10 p-4 text-sm">
            <AlertTriangle className="size-5 shrink-0 text-destructive" aria-hidden />
            {summary.invalid
              ? `The stored ${meta.label} doesn't match its template, so it can't be shown.`
              : `${meta.label} couldn't be generated.`}
          </div>
        ) : (
          <TemplateBody template={template} content={summary.content} />
        )}
      </div>
    </div>
  );
}

// Says honestly where the content came from.
function Provenance({ summary }: { summary: SummaryView }) {
  const text = summary.isSample
    ? "Sample content, shown because AI isn't configured"
    : summary.model
      ? `Generated by ${summary.model}`
      : "Written from the transcript, not AI-generated";
  return <p className="mt-0.5 text-xs text-muted-foreground">{text}</p>;
}

function Empty({ children }: { children: React.ReactNode }) {
  return (
    <div className="flex flex-col items-center gap-2 rounded-xl border border-dashed px-4 py-10 text-center text-sm text-muted-foreground">
      <FileText className="size-6" aria-hidden />
      {children}
    </div>
  );
}

type Point = { text: string };

function Points({ points, ordered = false }: { points: Point[]; ordered?: boolean }) {
  const List = ordered ? "ol" : "ul";
  return (
    <List className="grid gap-2">
      {points.map((p, i) => (
        <li key={i} className="flex items-start gap-2">
          <span
            aria-hidden
            className={cn(
              "mt-[0.55em] shrink-0 text-muted-foreground",
              ordered ? "-mt-px text-xs font-semibold" : "size-1.5 rounded-full bg-muted-foreground/70",
            )}
          >
            {ordered ? `${i + 1}.` : null}
          </span>
          <span className="flex-1 leading-relaxed">{p.text}</span>
        </li>
      ))}
    </List>
  );
}

function Block({ title, children, empty }: { title: string; children: React.ReactNode; empty?: boolean }) {
  return (
    <section className="grid gap-2">
      <h3 className="border-b pb-1 text-sm font-semibold tracking-tight text-foreground">{title}</h3>
      {empty ? <p className="text-muted-foreground">None recorded.</p> : children}
    </section>
  );
}

function TemplateBody({ template, content }: { template: SummaryTemplate; content: unknown }) {
  switch (template) {
    case "AI_NOTES": {
      const c = content as SummaryContent<"AI_NOTES">;
      return (
        <div className="grid gap-5 text-sm leading-6">
          <p>{c.overview}</p>
          {c.sections.map((s) => (
            <Block key={s.heading} title={s.heading}>
              <Points points={s.points} />
            </Block>
          ))}
        </div>
      );
    }
    case "MEETING_MINUTES": {
      const c = content as SummaryContent<"MEETING_MINUTES">;
      return (
        <div className="grid gap-5 text-sm leading-6">
          <Block title="Attendees" empty={c.attendees.length === 0}>
            <p>{c.attendees.join(", ")}</p>
          </Block>
          <Block title="Agenda" empty={c.agenda.length === 0}>
            <ol className="grid list-inside list-decimal gap-1 marker:text-muted-foreground">
              {c.agenda.map((a) => (
                <li key={a}>{a}</li>
              ))}
            </ol>
          </Block>
          <Block title="Discussion" empty={c.discussion.length === 0}>
            <dl className="grid gap-3">
              {c.discussion.map((d) => (
                <div key={d.topic} className="rounded-lg border bg-background/40 p-3">
                  <dt className="font-semibold text-foreground">
                    {d.topic}
                  </dt>
                  <dd className="mt-1 leading-relaxed text-muted-foreground">{d.notes}</dd>
                </div>
              ))}
            </dl>
          </Block>
          <Block title="Decisions" empty={c.decisions.length === 0}>
            <Points points={c.decisions} />
          </Block>
          <Block title="Next steps" empty={c.nextSteps.length === 0}>
            <Points points={c.nextSteps} ordered />
          </Block>
        </div>
      );
    }
    case "SUMMARY": {
      const c = content as SummaryContent<"SUMMARY">;
      return (
        <div className="grid gap-5 text-sm leading-6">
          <p className="rounded-xl border-l-2 border-primary bg-accent/40 p-3 leading-relaxed">
            <span className="mr-1 font-semibold text-accent-foreground">TL;DR</span>
            {c.tldr}
          </p>
          <Block title="Key points">
            <Points points={c.keyPoints} />
          </Block>
        </div>
      );
    }
    case "CUSTOMER_FEEDBACK": {
      const c = content as SummaryContent<"CUSTOMER_FEEDBACK">;
      const tone = {
        positive: "bg-emerald-400/15 text-emerald-300",
        negative: "bg-red-400/15 text-red-300",
        neutral: "bg-secondary text-muted-foreground",
        mixed: "bg-amber-300/15 text-amber-200",
      } as const;
      return (
        <div className="grid gap-5 text-sm leading-6">
          <p className="leading-relaxed text-muted-foreground">{c.context}</p>
          <Block title="Feedback" empty={c.feedback.length === 0}>
            <ul className="grid gap-2">
              {c.feedback.map((f, i) => (
                <li key={i} className="rounded-lg border bg-background/40 p-3">
                  <div className="mb-1 flex items-center gap-2">
                    <span className="font-medium">{f.speaker ?? "Unknown speaker"}</span>
                    <span className={cn("rounded-full px-2 py-0.5 text-xs capitalize", tone[f.sentiment])}>
                      {f.sentiment}
                    </span>
                  </div>
                  <p className="leading-relaxed">{f.text}</p>
                </li>
              ))}
            </ul>
          </Block>
          <Block title="Pain points" empty={c.painPoints.length === 0}>
            <Points points={c.painPoints} />
          </Block>
          <Block title="Requests" empty={c.requests.length === 0}>
            <Points points={c.requests} />
          </Block>
        </div>
      );
    }
    case "PROJECT_MEETING": {
      const c = content as SummaryContent<"PROJECT_MEETING">;
      const status = {
        on_track: ["On track", "bg-emerald-400/15 text-emerald-300"],
        at_risk: ["At risk", "bg-amber-300/15 text-amber-200"],
        off_track: ["Off track", "bg-red-400/15 text-red-300"],
      } as const;
      return (
        <div className="grid gap-5 text-sm leading-6">
          <div className="flex flex-wrap items-start justify-between gap-2">
            <p className="leading-relaxed">
              <span className="font-semibold">Goal: </span>
              {c.goal}
            </p>
            {c.status ? (
              <span className={cn("rounded-full px-2.5 py-0.5 text-xs font-medium", status[c.status][1])}>
                {status[c.status][0]}
              </span>
            ) : (
              <span className="rounded-full bg-secondary px-2.5 py-0.5 text-xs text-muted-foreground">Status not stated</span>
            )}
          </div>
          <Block title="Workstreams" empty={c.workstreams.length === 0}>
            <div className="overflow-x-auto rounded-lg border">
              <table className="w-full text-left">
                <thead className="bg-muted/50 text-xs text-muted-foreground">
                  <tr>
                    <th className="px-3 py-2 font-medium">Workstream</th>
                    <th className="px-3 py-2 font-medium">Owner</th>
                    <th className="px-3 py-2 font-medium">Due</th>
                  </tr>
                </thead>
                <tbody className="divide-y">
                  {c.workstreams.map((w) => (
                    <tr key={w.name}>
                      <td className="px-3 py-2">{w.name}</td>
                      <td className="px-3 py-2 text-muted-foreground">{w.owner ?? "Unassigned"}</td>
                      <td className="px-3 py-2 whitespace-nowrap text-muted-foreground">{w.due ?? "—"}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </Block>
          <Block title="Risks" empty={c.risks.length === 0}>
            <ul className="grid gap-2">
              {c.risks.map((r) => (
                <li key={r.text} className="rounded-lg border border-amber-300/20 bg-amber-300/5 p-3">
                  <div className="flex items-start justify-between gap-2">
                    <p>{r.text}</p>
                  </div>
                  {r.mitigation && <p className="mt-1 text-muted-foreground">Mitigation: {r.mitigation}</p>}
                </li>
              ))}
            </ul>
          </Block>
          <Block title="Next milestone" empty={!c.nextMilestone}>
            {c.nextMilestone && <Points points={[c.nextMilestone]} />}
          </Block>
        </div>
      );
    }
  }
}
